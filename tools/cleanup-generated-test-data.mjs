import { loadContract, toRestFunctionName } from '../tests/helpers/contract.mjs';
import { callRestFunction } from '../tests/helpers/moodle-rest.mjs';

const generatedNamePattern = /^MoodlIA\b/i;
const generatedShortnamePattern = /^moodlia-/i;

function printHelp() {
  console.log(`Usage:
  npm run moodle:cleanup-generated
  npm run moodle:cleanup-generated:execute
  node tools/cleanup-generated-test-data.mjs --course-id=42 --execute
  node tools/cleanup-generated-test-data.mjs --category-id=12 --execute

Description:
  Lists or deletes Moodle courses and course categories generated by MoodlIA tests.
  The default mode is a dry run. Use --execute to delete matched data.

Safety:
  Courses are eligible only when fullname starts with "MoodlIA" or shortname starts with "moodlia-".
  Course categories are eligible only when name starts with "MoodlIA".
  Explicit ids are still checked against those generated-data markers before deletion.

Options:
  --execute              Delete matched generated data. Without this flag, only print the plan.
  --course-id=<ids>      Limit to comma-separated course ids. Can be repeated.
  --category-id=<ids>    Limit to comma-separated course category ids. Can be repeated.
  --course-limit=<n>     Maximum courses to inspect through the contract, default 200.
  --help                 Show this help text.
`);
}

function readOptionValue(args, index, name) {
  const prefix = `${name}=`;
  const current = args[index];
  if (current.startsWith(prefix)) {
    return {
      value: current.slice(prefix.length),
      consumed: 1
    };
  }

  if (current === name && args[index + 1] !== undefined) {
    return {
      value: args[index + 1],
      consumed: 2
    };
  }

  return null;
}

function parseIds(raw, optionName) {
  const values = String(raw)
    .split(',')
    .map((value) => value.trim())
    .filter(Boolean);
  const ids = values.map((value) => Number(value));
  const invalid = ids.find((value) => !Number.isInteger(value) || value <= 0);
  if (invalid !== undefined || ids.length !== values.length) {
    throw new Error(`${optionName} must contain positive integer ids.`);
  }
  return ids;
}

function parseArgs(args) {
  const options = {
    execute: false,
    courseIds: new Set(),
    categoryIds: new Set(),
    courseLimit: 200,
    help: false
  };

  for (let index = 0; index < args.length;) {
    const arg = args[index];

    if (arg === '--help' || arg === '-h') {
      options.help = true;
      index += 1;
      continue;
    }

    if (arg === '--execute') {
      options.execute = true;
      index += 1;
      continue;
    }

    const courseId = readOptionValue(args, index, '--course-id');
    if (courseId) {
      for (const id of parseIds(courseId.value, '--course-id')) {
        options.courseIds.add(id);
      }
      index += courseId.consumed;
      continue;
    }

    const categoryId = readOptionValue(args, index, '--category-id');
    if (categoryId) {
      for (const id of parseIds(categoryId.value, '--category-id')) {
        options.categoryIds.add(id);
      }
      index += categoryId.consumed;
      continue;
    }

    const courseLimit = readOptionValue(args, index, '--course-limit');
    if (courseLimit) {
      const value = Number(courseLimit.value);
      if (!Number.isInteger(value) || value < 1 || value > 200) {
        throw new Error('--course-limit must be an integer between 1 and 200.');
      }
      options.courseLimit = value;
      index += courseLimit.consumed;
      continue;
    }

    throw new Error(`Unknown option: ${arg}`);
  }

  return options;
}

function normalizeCourse(course) {
  return {
    course_id: Number(course.course_id ?? course.id),
    fullname: String(course.fullname ?? course.full_name ?? course.name ?? ''),
    shortname: String(course.shortname ?? course.short_name ?? ''),
    category_id: Number(course.category_id ?? course.category ?? 0),
    visible: Boolean(course.visible)
  };
}

function normalizeCategory(category) {
  return {
    category_id: Number(category.category_id ?? category.id),
    name: String(category.name ?? ''),
    parent_id: Number(category.parent_id ?? category.parent ?? 0),
    course_count: Number(category.course_count ?? category.coursecount ?? 0),
    visible: Boolean(category.visible)
  };
}

function normalizeCourses(payload) {
  const courses = Array.isArray(payload) ? payload : payload?.courses ?? [];
  return courses
    .map(normalizeCourse)
    .filter((course) => Number.isInteger(course.course_id) && course.course_id > 1);
}

function normalizeCategories(payload) {
  const categories = Array.isArray(payload) ? payload : payload?.categories ?? [];
  return categories
    .map(normalizeCategory)
    .filter((category) => Number.isInteger(category.category_id) && category.category_id > 0);
}

function isGeneratedCourse(course) {
  return generatedNamePattern.test(course.fullname) || generatedShortnamePattern.test(course.shortname);
}

function isGeneratedCategory(category) {
  return generatedNamePattern.test(category.name);
}

function selectMatches(items, selectedIds, isGenerated) {
  const hasExplicitIds = selectedIds.size > 0;
  return {
    matched: items.filter((item) => {
      const id = item.course_id ?? item.category_id;
      return (!hasExplicitIds || selectedIds.has(id)) && isGenerated(item);
    }),
    skipped_explicit_ids: hasExplicitIds
      ? items.filter((item) => {
        const id = item.course_id ?? item.category_id;
        return selectedIds.has(id) && !isGenerated(item);
      })
      : []
  };
}

function restName(contract, operationName) {
  return toRestFunctionName(contract, operationName);
}

async function call(contract, operationName, parameters = {}) {
  return callRestFunction(restName(contract, operationName), parameters);
}

async function deleteItems(items, deleteItem) {
  const deleted = [];
  const failed = [];

  for (const item of items) {
    try {
      const result = await deleteItem(item);
      deleted.push({
        ...item,
        deleted: result.deleted === true
      });
    } catch (error) {
      failed.push({
        ...item,
        error: error.message
      });
    }
  }

  return { deleted, failed };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    printHelp();
    return;
  }

  const contract = await loadContract();
  const initialCourses = normalizeCourses(await call(contract, 'get_courses', {
    limit: options.courseLimit
  }));
  const courseSelection = selectMatches(initialCourses, options.courseIds, isGeneratedCourse);
  const deletedCourses = options.execute
    ? await deleteItems(courseSelection.matched, (course) => call(contract, 'delete_course', {
      course_id: course.course_id
    }))
    : { deleted: [], failed: [] };
  const coursesAfterCourseCleanup = options.execute
    ? normalizeCourses(await call(contract, 'get_courses', {
      limit: options.courseLimit
    }))
    : initialCourses;
  const remainingCoursesByCategory = new Map();
  for (const course of coursesAfterCourseCleanup) {
    const categoryCourses = remainingCoursesByCategory.get(course.category_id) ?? [];
    categoryCourses.push(course);
    remainingCoursesByCategory.set(course.category_id, categoryCourses);
  }

  const categoryPayload = await call(contract, 'get_course_categories', {
    parent_id: -1
  });
  const categories = normalizeCategories(categoryPayload);
  const categorySelection = selectMatches(categories, options.categoryIds, isGeneratedCategory);
  const deletableCategories = categorySelection.matched.filter((category) =>
    !remainingCoursesByCategory.has(category.category_id)
  );
  const skippedNonEmptyCategories = categorySelection.matched
    .filter((category) => remainingCoursesByCategory.has(category.category_id))
    .map((category) => ({
      ...category,
      remaining_courses: remainingCoursesByCategory.get(category.category_id)
    }));
  const deletedCategories = options.execute
    ? await deleteItems(deletableCategories, (category) => call(contract, 'delete_course_category', {
      category_id: category.category_id
    }))
    : { deleted: [], failed: [] };

  const result = {
    dry_run: !options.execute,
    inspected: {
      courses: initialCourses.length,
      courses_after_course_cleanup: coursesAfterCourseCleanup.length,
      categories: categories.length
    },
    matched_courses: courseSelection.matched,
    deleted_courses: deletedCourses.deleted,
    failed_courses: deletedCourses.failed,
    skipped_explicit_course_ids: courseSelection.skipped_explicit_ids,
    matched_categories: categorySelection.matched,
    deleted_categories: deletedCategories.deleted,
    failed_categories: deletedCategories.failed,
    skipped_non_empty_categories: skippedNonEmptyCategories,
    skipped_explicit_category_ids: categorySelection.skipped_explicit_ids
  };

  console.log(JSON.stringify(result, null, 2));

  if (deletedCourses.failed.length > 0 || deletedCategories.failed.length > 0) {
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error(JSON.stringify({
    error: true,
    message: error.message
  }, null, 2));
  process.exitCode = 1;
});
